# Beecrowd 1017 - Gasto de Combustível
#
# Joaozinho quer calcular e mostrar a quantidade de litros de combustível gastos em uma viagem de carro, sendo que seu carro faz 12 KM/L. Como ele não sabe fazer um programa que resolva este problema, ele pediu a sua ajuda. Para efetuar o cálculo, deve-se fornecer o tempo gasto na viagem (em horas) e a velocidade média durante a mesma (em km/h). Assim, será possível obter a distância percorrida e, em seguida, calcular quantos litros seriam necessários. Mostre o valor com 3 casas decimais após o ponto.
#
# Entrada:
# A entrada contém dois inteiros. O primeiro é o tempo gasto na viagem (em horas) e o segundo é a velocidade média durante a mesma (em km/h).
#
# Saída:
# Imprima a quantidade de litros necessária para realizar a viagem, com três dígitos após o ponto decimal.
#
# Exemplos:
#   Exemplo 1
#   Entrada:
#     10
#     85
#   Saída:
#     70.833
#   Exemplo 2
#   Entrada:
#     2
#     92
#   Saída:
#     15.333
#   Exemplo 3
#   Entrada:
#     22
#     67
#   Saída:
#     122.833
