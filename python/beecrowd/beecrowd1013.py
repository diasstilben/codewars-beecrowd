# Faça um programa que leia três valores inteiros e apresente o maior dos três valores lidos seguido da mensagem "eh o maior".
#
# Entrada:
# O arquivo de entrada contém três valores inteiros, na mesma linha.
#
# Saída:
# Imprima o maior dos três valores seguido por um espaço e a mensagem "eh o maior".
#
# Exemplos:
#   Exemplo 1
#   Entrada:
#     7 14 106
#   Saída:
#     106 eh o maior
#   Exemplo 2
#   Entrada:
#     217 14 6
#   Saída:
#     217 eh o maior
